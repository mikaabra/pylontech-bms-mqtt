#!/usr/bin/env python3
"""Generate the bms-link-sniffer debug-parameter menus from the vendor XML.

Reproducible source of truth: BMS073-H17-BL08-16S-en-US.xml (the vendor
tool's parameter definitions, committed at the repo root). Two outputs:

  1. stdout: the yaml `options:` block for the "Debug Read Parameter"
     select — one label per u16-band parameter (0x07..0x7C), ascending.
  2. param_table.md next to this script: the full table (all bands) for
     operator reference - param debug reads print raw values; the table
     maps index -> name / scale / unit / XML default.

The select's yaml lambda maps active_index -> param as 0x07 + index;
run this script after any XML change - it REFUSES to emit options if the
band is not dense or any entry is not a u16 (ByteNum != 2), which would
silently break that mapping.
"""
from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
XML_PATH = HERE.parents[2] / "BMS073-H17-BL08-16S-en-US.xml"
BAND_FIRST, BAND_LAST = 0x07, 0x7C


def sanitize_unit(unit: str) -> str:
    return unit.replace("℃", "C").strip()


def label(idx: int, name: str, scale: str, unit: str) -> str:
    base = f"0x{idx:02X} {name}"
    unit = sanitize_unit(unit)
    scale = scale.strip() or "1"
    if scale == "1":
        return f"{base} ({unit})" if unit else base
    return f"{base} (x{scale} {unit})" if unit else f"{base} (x{scale})"


def load_entries() -> list[dict]:
    entries = []
    for e in ET.parse(XML_PATH).iter():
        if e.tag.split("}")[-1] != "int_para":
            continue
        d = {c.tag: (c.text or "").strip() for c in e}
        entries.append(d)
    return entries


def band_entries(entries: list[dict]) -> list[tuple[int, dict]]:
    out = {}
    for d in entries:
        idx = int(d["ParaIndex"], 16)
        if not (BAND_FIRST <= idx <= BAND_LAST):
            continue
        if d.get("ByteNum") != "2":
            raise SystemExit(f"param 0x{idx:02X}: ByteNum={d.get('ByteNum')} - not a u16 entry")
        if idx in out:
            raise SystemExit(f"param 0x{idx:02X}: duplicate in the u16 band")
        out[idx] = d
    missing = [i for i in range(BAND_FIRST, BAND_LAST + 1) if i not in out]
    if missing:
        raise SystemExit(f"u16 band not dense - missing: {[f'0x{i:02X}' for i in missing]}")
    return [(i, out[i]) for i in range(BAND_FIRST, BAND_LAST + 1)]


def yaml_options(band: list[tuple[int, dict]]) -> str:
    lines = [f"      - {label(i, d['Name'], d['Scale'], d['UnitName'])!r}".replace("'", '"', 2)
             for i, d in band]
    # double-quoted, prefixed to sit two options-level per yaml nesting
    return "\n".join(lines)


def write_table(entries: list[dict], band: list[tuple[int, dict]]) -> None:
    rows = []
    seen = set()
    for d in entries:
        idx = int(d["ParaIndex"], 16)
        rows.append((idx, d))
    rows.sort(key=lambda r: r[0])
    with (HERE / "param_table.md").open("w") as fh:
        fh.write("# BMS073 int-parameter table (from the vendor XML)\n\n")
        fh.write("Generated by `gen_param_menus.py` from `BMS073-H17-BL08-16S-en-US.xml` —")
        fh.write(" regenerate after any XML change.\n\n")
        fh.write("Reads publish RAW u16 values (the A222 block layout: char offset")
        fh.write(" `4*idx+4`, byte offset `2*idx+2` in INFO after the battery number;")
        fh.write(" 0x00–0x06 are 4-byte entries, 0x7D+ are bit-params/tail — neither")
        fh.write(" is in the firmware read surface).\n\n")
        fh.write("| ParaIndex | Name | Scale | Unit | XML default | In read select |\n")
        fh.write("|---|---|---|---|---|---|\n")
        for idx, d in rows:
            in_band = "yes" if BAND_FIRST <= idx <= BAND_LAST else "—"
            fh.write(f"| 0x{idx:02X} | {d['Name']} | {d['Scale']} | "
                     f"{sanitize_unit(d['UnitName'])} | {d.get('Value', '')} | {in_band} |\n")


def main() -> int:
    entries = load_entries()
    band = band_entries(entries)
    label_count = 0
    if len(sys.argv) > 1 and sys.argv[1] == "count":
        print(len(band))
    else:
        print(yaml_options(band))
        label_count = len(band)
        write_table(entries, band)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
